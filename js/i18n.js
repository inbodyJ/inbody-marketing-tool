/* ─── 언어 전환 엔진 ─────────────────────────────────────────────── */

function getCurrentLang() {
  return localStorage.getItem('inbody_lang') || 'ko';
}

function setLang(lang) {
  localStorage.setItem('inbody_lang', lang);
  // applyLang 내부에서 data-i18n 번역 + window.currentPageRender?.() 재렌더 모두 처리
  applyLang(lang);
}

/**
 * 번역 키로 텍스트 가져오기
 * 예: t('dashboard.title') → "대시보드" 또는 "Dashboard"
 */
function t(key) {
  const lang = getCurrentLang();
  const keys = key.split('.');
  let value = i18n[lang];
  for (const k of keys) {
    value = value?.[k];
  }
  return value ?? key;
}

/**
 * 페이지 전체에 번역 적용
 */
function applyLang(lang) {
  // 1. data-i18n 속성 텍스트 교체
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const val = t(el.getAttribute('data-i18n'));
    if (val) el.textContent = val;
  });

  // 2. option[data-i18n] — select 옵션 텍스트 교체 (textContent 덮어쓰기)
  document.querySelectorAll('option[data-i18n]').forEach(el => {
    const val = t(el.getAttribute('data-i18n'));
    if (val) el.textContent = val;
  });

  // 3. placeholder 교체
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const val = t(el.getAttribute('data-i18n-placeholder'));
    if (val) el.placeholder = val;
  });

  // 4. title(tooltip) 교체
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const val = t(el.getAttribute('data-i18n-title'));
    if (val) el.title = val;
  });

  // 5. html 콘텐츠 교체
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const val = t(el.getAttribute('data-i18n-html'));
    if (val) el.innerHTML = val;
  });

  // 6. 언어 토글 버튼 UI 업데이트
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  // 7. html lang 속성
  document.documentElement.lang = lang === 'ko' ? 'ko' : 'en';

  // 8. 동적 렌더링 함수 재실행 — 현재 페이지 IIFE가 window.currentPageRender 에 등록
  window.currentPageRender?.();
}

// 페이지 로드 시 자동 적용
document.addEventListener('DOMContentLoaded', () => {
  applyLang(getCurrentLang());
});

// window에 노출
window.t              = t;
window.setLang        = setLang;
window.getCurrentLang = getCurrentLang;
window.applyLang      = applyLang;
